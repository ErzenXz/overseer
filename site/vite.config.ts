import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { DOC_PAGES } from "./src/docs/nav.ts";

// A small multi-page site: each page is its own static HTML entry.
const pages = ["index", "features/index", "download/index", "security/index", "changelog/index"];

// Each docs page gets its own HTML entry too, so every URL has the right
// title and description before any script runs. They're written from
// src/docs/nav.ts (and gitignored) so the page list lives in one place.
const docEntries = DOC_PAGES.map((page) => (page.slug ? `docs/${page.slug}/index` : "docs/index"));
function writeDocEntries() {
  const escape = (text: string) => text.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
  DOC_PAGES.forEach((page, i) => {
    const file = resolve(__dirname, `${docEntries[i]}.html`);
    const url = `https://overseer.sh/docs/${page.slug ? `${page.slug}/` : ""}`;
    const title = page.slug ? `${page.title} · Overseer Docs` : "Overseer Docs";
    const html = `<!doctype html>
<!-- Generated by vite.config.ts from src/docs/nav.ts. Don't edit. -->
<html lang="en" class="light">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="color-scheme" content="light" />
    <meta name="theme-color" content="#ffffff" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
    <title>${escape(title)}</title>
    <meta name="description" content="${escape(page.description)}" />
    <link rel="canonical" href="${url}" />
    <meta property="og:type" content="article" />
    <meta property="og:site_name" content="Overseer" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${escape(title)}" />
    <meta property="og:description" content="${escape(page.description)}" />
    <meta property="og:image" content="https://overseer.sh/og.jpg" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:image" content="https://overseer.sh/og.jpg" />
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/pages/Docs.tsx"></script>
  </body>
</html>
`;
    if (existsSync(file) && readFileSync(file, "utf8") === html) return;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
  });
}

export default defineConfig(() => {
  writeDocEntries();
  return {
    plugins: [react(), tailwindcss()],
    build: {
      rollupOptions: {
        input: Object.fromEntries([...pages, ...docEntries].map((page) => [page.replace(/\/index$/, "") || "index", resolve(__dirname, `${page}.html`)])),
      },
    },
  };
});
